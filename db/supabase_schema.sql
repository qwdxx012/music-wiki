-- Music Wiki: схема базы данных Supabase (PostgreSQL).
--
-- Выполнить один раз в Supabase Dashboard -> SQL Editor.
-- Приложение обращается к базе по REST API (PostgREST) через ключ
-- service_role, поэтому RLS включён, а политик для anon нет: обычный
-- клиентский ключ не получит доступ к таблицам.

-- Исполнители (карточка артиста из MusicBrainz)
create table if not exists public.artists (
    mbid            text primary key,
    name            text not null,
    type            text,
    country         text,
    begin_date      text,
    end_date        text,
    disambiguation  text,
    updated_at      timestamptz not null default now()
);

-- Альбомы / релиз-группы, привязанные к исполнителю
create table if not exists public.albums (
    mbid            text primary key,
    title           text not null,
    primary_type    text,
    release_date    text,
    artist_mbid     text not null references public.artists (mbid) on delete cascade,
    updated_at      timestamptz not null default now()
);
create index if not exists idx_albums_artist on public.albums (artist_mbid);

-- Треки / записи (recording), опционально привязанные к альбому
create table if not exists public.tracks (
    mbid                text primary key,
    title               text not null,
    length_ms           integer,
    first_release_date  text,
    album_mbid          text references public.albums (mbid) on delete set null,
    updated_at          timestamptz not null default now()
);
create index if not exists idx_tracks_album on public.tracks (album_mbid);

-- Справочник жанров/тегов
create table if not exists public.genres (
    id      bigint generated by default as identity primary key,
    name    text not null unique
);

-- Жанры исполнителя (M:N)
create table if not exists public.artist_genres (
    artist_mbid text not null references public.artists (mbid) on delete cascade,
    genre_id    bigint not null references public.genres (id) on delete cascade,
    primary key (artist_mbid, genre_id)
);

-- Жанры трека (M:N)
create table if not exists public.track_genres (
    track_mbid  text not null references public.tracks (mbid) on delete cascade,
    genre_id    bigint not null references public.genres (id) on delete cascade,
    primary key (track_mbid, genre_id)
);

-- Факты блока "Этот день в истории музыки"
create table if not exists public.facts (
    id          bigint generated by default as identity primary key,
    month_day   text not null,
    year        integer,
    text        text not null,
    source      text not null,
    artist_mbid text references public.artists (mbid) on delete set null,
    album_mbid  text references public.albums (mbid) on delete set null
);
create index if not exists idx_facts_month_day on public.facts (month_day);

-- Журнал распознаваний по аудио (AudD)
create table if not exists public.recognitions (
    id              bigint generated by default as identity primary key,
    recognized_at   timestamptz not null default now(),
    artist_name     text not null,
    track_title     text not null,
    score           double precision,
    track_mbid      text references public.tracks (mbid) on delete set null,
    source          text not null default 'audd'
);

-- Журнал поисковых запросов
create table if not exists public.search_queries (
    id              bigint generated by default as identity primary key,
    query_text      text,
    kind            text not null,
    genre           text,
    results_count   integer not null default 0,
    searched_at     timestamptz not null default now()
);
create index if not exists idx_search_kind on public.search_queries (kind);

-- Технический key-value кэш ответов MusicBrainz / Last.fm / AudD
create table if not exists public.cache (
    key         text primary key,
    value       jsonb not null,
    expires_at  double precision not null
);
create index if not exists idx_cache_expires on public.cache (expires_at);

-- Индекс дат релизов для блока "Этот день в истории музыки":
-- альбомы, которые уже встречались на открытых страницах артистов
create table if not exists public.release_dates (
    rg_id       text primary key,
    title       text not null,
    artist_id   text,
    artist_name text,
    rg_type     text,
    date        text not null,
    month_day   text not null
);
create index if not exists idx_release_md on public.release_dates (month_day);

-- Аналитические представления: PostgREST не умеет GROUP BY,
-- поэтому агрегаты считает база, а приложение просто читает view
create or replace view public.top_searches as
select query_text, kind, count(*)::int as n
from public.search_queries
where query_text is not null and query_text <> ''
group by query_text, kind;

create or replace view public.artists_album_counts as
select a.name, a.country, count(al.mbid)::int as albums
from public.artists a
left join public.albums al on al.artist_mbid = a.mbid
group by a.mbid, a.name, a.country;

-- Доступ: приложение ходит под service_role (обходит RLS).
-- Для anon и authenticated политик нет, поэтому таблицы им закрыты.
alter table public.artists       enable row level security;
alter table public.albums        enable row level security;
alter table public.tracks        enable row level security;
alter table public.genres        enable row level security;
alter table public.artist_genres enable row level security;
alter table public.track_genres  enable row level security;
alter table public.facts         enable row level security;
alter table public.recognitions  enable row level security;
alter table public.search_queries enable row level security;
alter table public.cache         enable row level security;
alter table public.release_dates enable row level security;

grant usage on schema public to anon, authenticated, service_role;
grant all on all tables in schema public to service_role;
grant all on public.release_dates to service_role;
grant all on all sequences in schema public to service_role;
grant select on public.top_searches, public.artists_album_counts to service_role;
revoke all on public.top_searches, public.artists_album_counts from anon, authenticated;

-- Сообщаем PostgREST, что появились новые таблицы и представления
notify pgrst, 'reload schema';
